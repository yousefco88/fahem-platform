// دمج عميق بسيط: قيم القاعدة تتقدم على الافتراضي، مع الحفاظ على الحقول الناقصة
export function mergeSettings(defaults, overrides) {
  if (!overrides || typeof overrides !== 'object') return defaults;
  if (Array.isArray(defaults) || Array.isArray(overrides)) return overrides;
  const out = { ...defaults };
  for (const k of Object.keys(overrides)) {
    const d = defaults?.[k];
    const o = overrides[k];
    out[k] = (d && typeof d === 'object' && !Array.isArray(d) && o && typeof o === 'object' && !Array.isArray(o))
      ? mergeSettings(d, o)
      : o;
  }
  return out;
}
